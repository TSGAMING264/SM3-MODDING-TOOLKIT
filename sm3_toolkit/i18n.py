def normalize_language(language: str | None) -> str:
    if language in LANGUAGE_NAMES:
        return str(language)
    return DEFAULT_LANGUAGE


def tr(language: str | None, key: str) -> str:
    lang = normalize_language(language)
    return TEXT.get(lang, TEXT[DEFAULT_LANGUAGE]).get(key, TEXT[DEFAULT_LANGUAGE].get(key, key))


def tab_labels(language: str | None) -> List[str]:
    return [tr(language, f"tab.{key}") for key in TAB_KEYS]


def how_to_text(language: str | None, english_detail: str) -> str:
    lang = normalize_language(language)
    if lang == DEFAULT_LANGUAGE:
        return english_detail
    return tr(lang, "how_local") + "\n\n" + "=" * 80 + "\nREFERENCE / BUTTON NAMES IN ENGLISH\n" + "=" * 80 + "\n" + english_detail
